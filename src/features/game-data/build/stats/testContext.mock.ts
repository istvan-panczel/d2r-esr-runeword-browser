const tsv = (rows: readonly (readonly string[])[]) => rows.map((row) => row.join('\t')).join('\n');

const PROPERTY_COLUMNS = [
  'code',
  '*Id',
  ...[1, 2, 3, 4, 5, 6, 7].flatMap((i) => [`func${String(i)}`, `stat${String(i)}`, `set${String(i)}`, `val${String(i)}`]),
];
/** [code, ...[func, stat, set, val] per slot] */
const prop = (code: string, ...slots: [number, string, number?, number?][]) => [
  code,
  '0',
  ...slots.flatMap(([func, stat, set, val]) => [
    String(func),
    stat,
    set === undefined ? '' : String(set),
    val === undefined ? '' : String(val),
  ]),
];

const STAT_COLUMNS = [
  'Stat',
  'op',
  'op param',
  'descpriority',
  'descfunc',
  'descval',
  'descstrpos',
  'descstrneg',
  'descstr2',
  'dgrp',
  'dgrpfunc',
  'dgrpval',
  'dgrpstrpos',
  'dgrpstrneg',
  'dgrpstr2',
];
/** [stat, op, opParam, priority, descfunc, descval, pos, neg, str2, dgrp, dgrpfunc, dgrpval, dgrppos, dgrpneg, dgrpstr2] */
const stat = (
  name: string,
  priority: number,
  descfunc: number,
  descval: number,
  pos: string,
  extra: Partial<Record<string, string | number>> = {}
) =>
  STAT_COLUMNS.map((column) => {
    if (column === 'Stat') return name;
    if (column === 'descpriority') return String(priority);
    if (column === 'descfunc') return String(descfunc);
    if (column === 'descval') return String(descval);
    if (column === 'descstrpos') return pos;
    if (column === 'descstrneg') return String(extra.descstrneg ?? pos);
    const value = extra[column];
    return value === undefined ? '' : String(value);
  });

